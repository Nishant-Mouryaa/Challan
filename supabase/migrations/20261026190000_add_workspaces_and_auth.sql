revoke all on public.workspaces, public.workspace_memberships,
  public.business_records, public.documents, public.legacy_workspace_claims
  from anon, authenticated;
revoke all on function public.create_workspace_for_new_user() from public, anon, authenticated;
revoke all on function public.user_can_access_workspace(uuid) from public, anon;
grant execute on function public.user_can_access_workspace(uuid) to authenticated;

grant select on public.workspaces, public.workspace_memberships to authenticated;
grant select, insert, update, delete
  on public.business_records, public.documents to authenticated;

grant usage, select on sequence public.business_records_id_seq to authenticated;

drop policy if exists workspace_members_can_read_workspaces on public.workspaces;
create policy workspace_members_can_read_workspaces
  on public.workspaces for select to authenticated
  using (public.user_can_access_workspace(id));

drop policy if exists users_can_read_own_membership on public.workspace_memberships;
create policy users_can_read_own_membership
  on public.workspace_memberships for select to authenticated
  using (user_id = auth.uid());

drop policy if exists workspace_members_manage_business_records on public.business_records;
create policy workspace_members_manage_business_records
  on public.business_records for all to authenticated
  using (public.user_can_access_workspace(workspace_id))
  with check (public.user_can_access_workspace(workspace_id));

drop policy if exists workspace_members_manage_documents on public.documents;
create policy workspace_members_manage_documents
  on public.documents for all to authenticated
  using (public.user_can_access_workspace(workspace_id))
  with check (public.user_can_access_workspace(workspace_id));
