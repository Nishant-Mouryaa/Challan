create or replace function public.create_workspace_for_new_user()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  claimed_workspace_id uuid;
  business_name text;
begin
  business_name := trim(coalesce(new.raw_user_meta_data ->> 'business_name', ''));
  if char_length(business_name) < 2 or char_length(business_name) > 120 then
    raise exception 'A business name between 2 and 120 characters is required';
  end if;

  select workspace_id
    into claimed_workspace_id
    from public.legacy_workspace_claims
    where owner_email = lower(new.email)
    for update;

  if claimed_workspace_id is not null then
    update public.workspaces
      set name = business_name
      where id = claimed_workspace_id;

    insert into public.workspace_memberships (workspace_id, user_id, role)
    values (claimed_workspace_id, new.id, 'owner');

    delete from public.legacy_workspace_claims
      where owner_email = lower(new.email);
  else
    insert into public.workspaces (name)
    values (business_name)
    returning id into claimed_workspace_id;

    insert into public.workspace_memberships (workspace_id, user_id, role)
    values (claimed_workspace_id, new.id, 'owner');
  end if;

  return new;
end;
$$;

